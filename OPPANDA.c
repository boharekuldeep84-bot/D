// ---------- Expiry Check ----------
void check_expiry(int year, int month, int day) {
    struct tm expiry_tm = {0};
    time_t current_time = time(NULL);

    expiry_tm.tm_year = year - 1900;
    expiry_tm.tm_mon  = month - 1;
    expiry_tm.tm_mday = day;
    expiry_tm.tm_hour = 0;
    expiry_tm.tm_min  = 0;
    expiry_tm.tm_sec  = 0;

    time_t expiry_time = mktime(&expiry_tm);

    if (expiry_time == -1) {
        perror("mktime failed");
        exit(EXIT_FAILURE);
    }

    if (current_time > expiry_time) {
        printf("This file is closed. Please contact @GG_CEO\n");
        exit(EXIT_FAILURE);
    }
}

